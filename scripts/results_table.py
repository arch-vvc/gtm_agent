"""Turn results/real_results.csv into the Markdown table in the README Results section.

Usage from the repo root:

    python -m scripts.results_table [--csv PATH] [--readme PATH] [--write-readme | --check]

By default the table goes to stdout. With --write-readme it replaces everything
between the two results marker lines in the README. With --check it exits 0 when
the README already holds exactly this table and 1 when it does not. Only the
standard library and pitch are imported, so no API keys are needed.
"""

import argparse
import csv
import re
import sys
from pathlib import Path

import pitch

START_MARKER = "<!-- results:start -->"
END_MARKER = "<!-- results:end -->"
HEADERS = [
    "Company",
    "Cluster",
    "Demo",
    "Hiring FDE",
    "Cluster reason (quoted from the site)",
    "Note (first line)",
    "What the automatic checks found",
]
NOTE_LIMIT = 220
REASON_LIMIT = 160
NOTHING_FOUND = "none found by the automatic checks"
FOOTNOTE = (
    "_Generated by scripts/results_table.py from results/real_results.csv. "
    "The automatic checks look at names, figures, dashes, the note length and made up claims of past work. "
    "They do not prove a note is true, read every note before sending it._"
)
# U+2010 to U+2015 (hyphen, non breaking hyphen, figure dash, en dash, em dash, horizontal bar) and U+2212 (minus).
DASH_LIKE = re.compile("[\u2010-\u2015\u2212]")
SPACED_HYPHEN = re.compile(r"\s-\s")
FORMULA_GUARD = re.compile(r"^'(?=[=+\-@])")


def clean(value):
    """Return one line of plain text: no newlines, no dash like characters, no repeated spaces."""
    text = FORMULA_GUARD.sub("", value or "")
    text = DASH_LIKE.sub(" ", text)
    text = text.replace("\r", " ").replace("\n", " ")
    text = SPACED_HYPHEN.sub(" ", text)
    return " ".join(text.split())


def shorten(text, limit):
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + "..."


def first_line(note):
    for line in (note or "").splitlines():
        if line.strip():
            return line
    return ""


def hiring_label(value):
    return {"true": "yes", "false": "no"}.get((value or "").strip().lower(), "unknown")


# Model text is untrusted and ends up in a public README. Characters that could
# start a link, an image or a code span (and the backslash itself) get one
# backslash in front. The ampersand and angle brackets become the HTML entities
# &amp; &lt; &gt; so no raw tag survives. This runs once per piece of model
# text, on the shortened text; the fixed text of the table (headers, prefixes,
# footnote) is never escaped. Pipes are escaped separately in markdown_line.
MD_BACKSLASH = re.compile(r"([\\\[\]()!`])")
HTML_ENTITIES = {"&": "&amp;", "<": "&lt;", ">": "&gt;"}


def md_escape(text):
    text = MD_BACKSLASH.sub(r"\\\1", text)
    return "".join(HTML_ENTITIES.get(char, char) for char in text)


def findings(row):
    """List what went wrong in one row, or the text saying the automatic checks found nothing."""
    found = []
    if clean(row.get("error")):
        found.append("failed: " + md_escape(clean(row["error"])))
    if clean(row.get("pitch_error")):
        found.append("note rejected: " + md_escape(clean(row["pitch_error"])))
    note = row.get("pitch_note") or ""
    if note.strip():
        found += [md_escape(clean(item)) for item in pitch.check_pitch_claims(note)]
        found += [md_escape(clean(item)) for item in pitch.check_pitch_note(note)]
    return "; ".join(found) or NOTHING_FOUND


def table_cells(row):
    note = shorten(clean(first_line(row.get("pitch_note"))), NOTE_LIMIT)
    reason = shorten(clean(row.get("cluster_reason")), REASON_LIMIT)
    return [
        md_escape(clean(row.get("name")) or clean(row.get("url")) or "n/a"),
        md_escape(clean(row.get("cluster")) or "n/a"),
        md_escape(clean(row.get("demo")) or "n/a"),
        hiring_label(row.get("hiring_fde")),
        md_escape(reason),
        md_escape(note),
        findings(row),
    ]


def escape_pipes(text):
    return text.replace("|", "\\|")


def markdown_line(cells):
    return "| " + " | ".join(escape_pipes(cell) for cell in cells) + " |"


def read_rows(path):
    """Read the CSV (a UTF-8 BOM is allowed). Raise ValueError when a needed column is missing."""
    with open(path, encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        names = reader.fieldnames or []
        if "pitch_note" not in names:
            raise ValueError("column pitch_note is missing")
        if "name" not in names and "url" not in names:
            raise ValueError("columns name and url are both missing")
        return list(reader)


def build_block(rows):
    """Return the Markdown that goes between the markers, without the marker lines."""
    if not rows:
        return "No rows yet."
    lines = [markdown_line(HEADERS), "|" + "---|" * len(HEADERS)]
    lines += [markdown_line(table_cells(row)) for row in rows]
    return "\n".join(lines) + "\n\n" + FOOTNOTE


def split_readme(text):
    """Return (before, inside, after) around the markers, or raise ValueError with a clear message."""
    if text.count(START_MARKER) != 1 or text.count(END_MARKER) != 1:
        raise ValueError(f"the README must contain {START_MARKER} and {END_MARKER} exactly once each")
    start = text.index(START_MARKER) + len(START_MARKER)
    end = text.index(END_MARKER)
    if end < start:
        raise ValueError(f"{END_MARKER} comes before {START_MARKER} in the README")
    return text[:start], text[start:end], text[end:]


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="python -m scripts.results_table",
        description="Build the README results table from the results CSV.",
    )
    parser.add_argument("--csv", default="results/real_results.csv", help="results CSV (default: %(default)s)")
    parser.add_argument("--readme", default="README.md", help="README to update or check (default: %(default)s)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write-readme", action="store_true", help="replace the block between the results markers")
    mode.add_argument("--check", action="store_true", help="exit 1 when the README block differs from the CSV")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    csv_path = Path(args.csv)
    if not csv_path.is_file():  # also true for a directory
        print(f"error: results file {csv_path} not found", file=sys.stderr)
        return 1
    try:
        block = build_block(read_rows(csv_path))
    except (UnicodeDecodeError, OSError, ValueError) as error:
        print(f"error: cannot read results file {csv_path}: {error}", file=sys.stderr)
        return 1
    if not (args.write_readme or args.check):
        print(block)
        return 0
    readme_path = Path(args.readme)
    if not readme_path.is_file():
        print(f"error: README {readme_path} not found", file=sys.stderr)
        return 1
    try:
        text = readme_path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError) as error:
        print(f"error: cannot read README {readme_path}: {error}", file=sys.stderr)
        return 1
    try:
        before, inside, after = split_readme(text)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    wanted = "\n" + block + "\n"
    if args.check:
        if inside == wanted:
            return 0
        print("README results block is out of date, run: python -m scripts.results_table --write-readme")
        return 1
    try:
        readme_path.write_text(before + wanted + after, encoding="utf-8")
    except OSError as error:
        print(f"error: cannot write README {readme_path}: {error}", file=sys.stderr)
        return 1
    print(f"README results block updated from {csv_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
